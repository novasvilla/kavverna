const RESTING: [u8; 3] = [0xDC, 0xDC, 0xDC];
const AWAKE: [u8; 3] = [0xE9, 0xB4, 0x4C];

/// Straight rather than premultiplied alpha, which is what a StatusNotifierItem pixmap carries,
/// so the edge pixels keep the full colour and fade only through their alpha.
fn draw(colour: [u8; 3], edge: i32, coverage: &[u8]) -> Icon {
    let [red, green, blue] = colour;
    let data = coverage.iter().flat_map(|&alpha| [alpha, red, green, blue]).collect();

    Icon { width: edge, height: edge, data }
}

/// Several sizes so the panel can pick one without resampling on a HiDPI screen.
pub fn mark(awake: bool) -> Vec<Icon> {
    let colour = if awake { AWAKE } else { RESTING };
    vec![draw(colour, 22, &MARK_22), draw(colour, 44, &MARK_44)]
}

#[cfg(test)]
mod tests {
    use super::*;

    fn alpha(icon: &Icon) -> Vec<u8> {
        icon.data.chunks(4).map(|pixel| pixel[0]).collect()
    }

    #[test]
    fn both_sizes_are_whole_square_pixmaps() {
        let icons = mark(false);
        let edges: Vec<i32> = icons.iter().map(|icon| icon.width).collect();

        assert_eq!(edges, [22, 44]);
        for icon in &icons {
            assert_eq!(icon.width, icon.height);
            assert_eq!(icon.data.len(), (icon.width * icon.height * 4) as usize);
        }
    }

    #[test]
    fn the_mark_carries_its_state_in_colour_alone() {
        for (resting, awake) in mark(false).iter().zip(mark(true).iter()) {
            assert_eq!(alpha(resting), alpha(awake), "the two states drew different shapes");
            assert_ne!(resting.data, awake.data, "both states drew the same colour");
        }
    }

    #[test]
    fn a_margin_stays_clear_on_every_side() {
        for icon in mark(false) {
            let edge = icon.width as usize;
            let margin = edge * 3 / 22;
            let coverage = alpha(&icon);

            for y in 0..edge {
                for x in 0..edge {
                    let inside = (margin..edge - margin).contains(&x)
                        && (margin..edge - margin).contains(&y);
                    if !inside {
                        assert_eq!(coverage[y * edge + x], 0, "{edge} px icon drew at {x},{y}");
                    }
                }
            }
        }
    }

    #[test]
    fn edges_are_smoothed_and_the_body_is_solid() {
        for icon in mark(false) {
            let coverage = alpha(&icon);
            assert!(coverage.contains(&255), "{} px icon has no solid body", icon.width);
            assert!(
                coverage.iter().any(|&a| a > 0 && a < 255),
                "{} px icon has hard edges",
                icon.width
            );
        }
    }

    #[test]
    fn the_large_icon_is_drawn_rather_than_doubled() {
        let doubled: Vec<u8> =
            (0..44 * 44).map(|index| MARK_22[(index / 44 / 2) * 22 + (index % 44) / 2]).collect();

        assert_ne!(MARK_44.to_vec(), doubled);
    }
}
